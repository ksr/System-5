#!/usr/bin/env python3
# Author: Claude (Anthropic) for Ken Rother's System-5 project, 2026-11-01
"""Generate src/tables.inc: GBASIC's keyword tokens, names, match index, statement dispatch and operator tables.

Tokens are numbered from 80h in the order of KEYWORDS below (statements first, so the dispatch table is indexed by
token - 80h).  The tokenizer looks keywords up by their first letter (KWFIRST/KWLIST, longest first so INPUT wins
over INP); LIST finds a token's name through KWADDR.  The name strings end with bit 7 set on the last character.
"""
import os, sys

# (keyword, handler label or None).  Statements first (they have handlers), then the rest.
STATEMENTS = [
    ("END", "st_end"), ("FOR", "st_for"), ("NEXT", "st_next"), ("DATA", "st_rem_data"), ("INPUT", "st_input"),
    ("DIM", "st_dim"), ("READ", "st_read"), ("LET", "st_let"), ("GOTO", "st_goto"), ("RUN", "st_run"),
    ("IF", "st_if"), ("RESTORE", "st_restore"), ("GOSUB", "st_gosub"), ("RETURN", "st_return"),
    ("REM", "st_rem"), ("'", "st_rem"), ("STOP", "st_stop"), ("ON", "st_on"), ("PRINT", "st_print"),
    ("LIST", "st_list"), ("CLEAR", "st_clear"), ("NEW", "st_new"), ("CONT", "st_cont"), ("POKE", "st_poke"),
    ("OUT", "st_out"), ("CLS", "st_cls"), ("SAVE", "st_save"), ("LOAD", "st_load"), ("FILES", "st_files"),
    ("DIR", "st_files"), ("BYE", "st_bye"), ("DELETE", "st_delete"), ("RENUM", "st_renum"), ("ELSE", "st_rem"),
    ("GRAPHICS", "st_graphics"), ("TEXT", "st_text"), ("MIX", "st_mix"), ("PAGE", "st_page"), ("PEN", "st_pen"),
    ("PSET", "st_pset"), ("DOT", "st_pset"), ("ERASE", "st_erase"), ("LINE", "st_line"), ("BOX", "st_box"),
    ("CIRCLE", "st_circle"), ("ELLIPSE", "st_ellipse"), ("WAIT", "st_wait"), ("RANDOMIZE", "st_randomize"),
    ("CALL", "st_call"), ("KILL", "st_kill"), ("LOCATE", "st_locate"),
]
OTHERS = ["THEN", "TO", "STEP", "OFF", "TAB(", "SPC(", "CHR$("]
FUNCTIONS = [("ABS", "fn_abs"), ("SGN", "fn_sgn"), ("RND", "fn_rnd"), ("PEEK", "fn_peek"), ("INP", "fn_inp"),
             ("USR", "fn_usr"), ("FRE", "fn_fre"), ("POINT", "fn_point"), ("INKEY", "fn_inkey")]
# binary operators: (text, precedence, handler); NOT is unary (handled in the parser), after them
OPERATORS = [("OR", 1, "op_or"), ("XOR", 1, "op_xor"), ("AND", 2, "op_and"), ("=", 3, "op_eq"), ("<>", 3, "op_ne"),
             ("<", 3, "op_lt"), (">", 3, "op_gt"), ("<=", 3, "op_le"), (">=", 3, "op_ge"), ("+", 4, "op_add"),
             ("-", 4, "op_sub"), ("*", 5, "op_mul"), ("/", 5, "op_div"), ("MOD", 5, "op_mod")]
UNARY = ["NOT"]

NAMES = {"'": "REM2", "TAB(": "TAB", "SPC(": "SPC", "CHR$(": "CHR", "=": "EQ", "<>": "NE", "<": "LT", ">": "GT",
         "<=": "LE", ">=": "GE", "+": "PLUS", "-": "MINUS", "*": "MUL", "/": "DIV"}


def tkname(k): return "TK_" + NAMES.get(k, k)


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "tables.inc")
    words = [k for k, _ in STATEMENTS] + OTHERS + [k for k, _ in FUNCTIONS] + [k for k, _, _ in OPERATORS] + UNARY
    assert len(set(words)) == len(words), "duplicate keyword"
    tok = {k: 0x80 + i for i, k in enumerate(words)}
    assert max(tok.values()) <= 0xFF
    L = ["; Generated by software/gbasic/tools/gen_tables.py - do not edit by hand.", ""]
    for k in words: L.append("%-12s equ 0%02Xh" % (tkname(k), tok[k]))
    L.append("STMT_LAST    equ 0%02Xh" % tok[STATEMENTS[-1][0]])
    L.append("FN_FIRST     equ 0%02Xh" % tok[FUNCTIONS[0][0]])
    L.append("FN_LAST      equ 0%02Xh" % tok[FUNCTIONS[-1][0]])
    L.append("OP_FIRST     equ 0%02Xh" % tok[OPERATORS[0][0]])
    L.append("OP_LAST      equ 0%02Xh" % tok[OPERATORS[-1][0]])
    L.append("TK_LASTKW    equ 0%02Xh" % tok[words[-1]])
    L.append("")
    # names
    L.append("; keyword names, last character + 80h")
    for k in words:
        chars = [ord(c) for c in k]; chars[-1] |= 0x80
        L.append("kw_%02x:      db %s   ; %s" % (tok[k], ",".join("0%02Xh" % c for c in chars), k))
    L.append("")
    L.append("; token -> name")
    L.append("kwaddr:")
    for i in range(0, len(words), 8):
        L.append("            dw " + ",".join("kw_%02x" % tok[k] for k in words[i:i + 8]))
    L.append("")
    # first-letter index: only keywords that start with a letter take part in matching
    alpha = [k for k in words if k[0].isalpha()]
    match = []; first = []
    for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        first.append(len(match))
        group = sorted([k for k in alpha if k[0] == c], key=lambda k: -len(k))
        match += [tok[k] for k in group]
    first.append(len(match))
    L.append("; keyword matching: KWLIST[KWFIRST[letter] .. KWFIRST[letter+1]-1] are the tokens starting with it")
    L.append("kwfirst:     db " + ",".join("%d" % x for x in first))
    L.append("kwlist:")
    for i in range(0, len(match), 12):
        L.append("            db " + ",".join("0%02Xh" % t for t in match[i:i + 12]))
    L.append("")
    L.append("; statement handlers, by token - 80h")
    L.append("stmttab:")
    for k, h in STATEMENTS: L.append("            dw %-14s ; %s" % (h, k))
    L.append("")
    L.append("; functions, by token - FN_FIRST")
    L.append("fntab:")
    for k, h in FUNCTIONS: L.append("            dw %-14s ; %s" % (h, k))
    L.append("")
    L.append("; binary operators, by token - OP_FIRST: precedence, then handler")
    L.append("prectab:     db " + ",".join(str(p) for _, p, _ in OPERATORS))
    L.append("optab:")
    for k, p, h in OPERATORS: L.append("            dw %-14s ; %s" % (h, k))
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote %s: %d keywords, tokens 80h-%02Xh" % (os.path.relpath(out), len(words), max(tok.values())))


if __name__ == "__main__":
    main()
